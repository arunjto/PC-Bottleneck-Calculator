import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import ts from 'typescript';

const root = process.cwd();
const sourcePath = path.join(root, 'lib', 'hardware-database.ts');
const outputPath = path.join(root, 'lib', 'hardware-client-data.ts');
const source = fs.readFileSync(sourcePath, 'utf8');
const compiled = ts.transpileModule(source, {
  compilerOptions: {
    module: ts.ModuleKind.CommonJS,
    target: ts.ScriptTarget.ES2020,
  },
}).outputText;

const moduleRecord = { exports: {} };
vm.runInNewContext(
  `(function(exports, module, require) {${compiled}\n})(moduleRecord.exports, moduleRecord, require);`,
  { moduleRecord, require: () => { throw new Error('Unexpected generated import'); } },
  { filename: sourcePath },
);
const database = moduleRecord.exports;

const cpuFields = [
  'id', 'name', 'brand', 'series', 'baseClock', 'boostClock', 'cores', 'threads',
  'tdp', 'benchmarkScore', 'releaseYear', 'launchPrice', 'currentPrice', 'tier', 'category',
  'socket', 'architecture', 'officialUrl',
];
const gpuFields = [
  'id', 'name', 'brand', 'series', 'vram', 'baseClock', 'boostClock', 'tdp',
  'benchmarkScore', 'releaseYear', 'launchPrice', 'currentPrice', 'tier', 'category',
  'architecture', 'officialUrl',
];
const gameFields = [
  'id', 'name', 'releaseYear', 'category', 'cpuDemand', 'gpuDemand',
  'ramRequirement', 'storageRequirement', 'optimizations',
];

function project(items, fields) {
  return items.map((item) => Object.fromEntries(
    fields.flatMap((field) => item[field] === undefined ? [] : [[field, item[field]]])
  ));
}

const cpus = project(database.allCPUs, cpuFields);
const gpus = project(database.allGPUs, gpuFields);
const games = project(database.allGames, gameFields);
const quoteKeys = (fields) => fields.map((field) => `'${field}'`).join(' | ');

const output = `// Generated by scripts/generate-client-hardware-data.mjs.
// Keep the authoritative records in lib/hardware-database.ts.
import type { CPU as FullCPU, GPU as FullGPU, Game as FullGame } from '@/lib/hardware-database';

export type CPU = Pick<FullCPU, ${quoteKeys(cpuFields)}>;
export type GPU = Pick<FullGPU, ${quoteKeys(gpuFields)}>;
export type Game = Pick<FullGame, ${quoteKeys(gameFields)}>;

export const HARDWARE_DATABASE_UPDATED = ${JSON.stringify(database.HARDWARE_DATABASE_UPDATED)};
export const HARDWARE_SCORE_METHODOLOGY_VERSION = ${JSON.stringify(database.HARDWARE_SCORE_METHODOLOGY_VERSION)};

export const allCPUs: CPU[] = ${JSON.stringify(cpus)};
export const allGPUs: GPU[] = ${JSON.stringify(gpus)};
export const allGames: Game[] = ${JSON.stringify(games)};

const cpuById = new Map(allCPUs.map((item) => [item.id, item]));
const gpuById = new Map(allGPUs.map((item) => [item.id, item]));
const gameById = new Map(allGames.map((item) => [item.id, item]));

export function getCPUById(id: string): CPU | undefined {
  return cpuById.get(id);
}

export function getGPUById(id: string): GPU | undefined {
  return gpuById.get(id);
}

export function getGameById(id: string): Game | undefined {
  return gameById.get(id);
}
`;

fs.writeFileSync(outputPath, output);
console.log(
  `Generated ${path.relative(root, outputPath)}: ${cpus.length} CPUs, ${gpus.length} GPUs, ${games.length} games (${Buffer.byteLength(output)} bytes).`
);
